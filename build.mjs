// Bundles the custom app into the shape Spicetify loads: a global plus `render()`.
import * as esbuild from 'esbuild';
import { cpSync, existsSync, mkdirSync, writeFileSync } from 'node:fs';

const opts = {
  entryPoints: ['src/app.jsx'],
  bundle: true,
  format: 'iife',
  globalName: 'cdshelf',
  outfile: 'dist/index.js',
  minify: !process.env.CDS_DEBUG,
  target: 'chrome120',
  jsxFactory: 'Spicetify.React.createElement',
  jsxFragment: 'Spicetify.React.Fragment',
  loader: { '.css': 'text', '.glb': 'dataurl', '.ttf': 'dataurl' },
  footer: { js: 'const render=()=>cdshelf.default();' },
  logLevel: 'info',
};

mkdirSync('dist', { recursive: true });

// The TV corner's models are licensed for use, not redistribution, so they live outside the source
// tree in assets/ and are bundled only when present. Without them the shelf builds without the corner.
const ASSETS = { tv: 'pvm_monitor.glb', ps2: 'ps1_console.glb', pad: 'ps1_pad.glb', table: 'table.glb', board: 'whiteboard.glb', tray: 'ashtray.glb', font: 'fonts/PermanentMarker-Regular.ttf' };
const lines = ['// Generated by build.mjs. Do not edit.'];
const names = [];
// CDS_ASSET_BASE=https://cdn.jsdelivr.net/gh/<you>/<repo>@<tag>/release-assets serves the models from there
// instead of embedding them (keeps the app file small for a public release). Unset: embedded.
const base = process.env.CDS_ASSET_BASE?.replace(/\/$/, '');
for (const [key, file] of Object.entries(ASSETS)) {
  // Only files that are actually in the hosted folder (release-assets/ by default).
  if (base) names.push(existsSync(`${process.env.CDS_ASSET_DIR || 'release-assets'}/${file}`) ? `${key}: ${JSON.stringify(`${base}/${file}`)}` : `${key}: null`);
  else if (existsSync(`assets/${file}`)) {
    lines.push(`import ${key} from '../assets/${file}';`);
    names.push(key);
  } else names.push(`${key}: null`);
}
lines.push(`export default { ${names.join(', ')} };`);
writeFileSync('src/assets.gen.js', lines.join('\n') + '\n');
cpSync('manifest.json', 'dist/manifest.json');
const ext = {
  ...opts,
  entryPoints: ['src/extension.js'],
  globalName: undefined,
  outfile: 'dist/extension.js',
  footer: undefined,
};
if (process.argv.includes('--watch')) {
  await (await esbuild.context(opts)).watch();
  await (await esbuild.context(ext)).watch();
} else await Promise.all([esbuild.build(opts), esbuild.build(ext)]);
