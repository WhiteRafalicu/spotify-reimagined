export const LANGUAGE_NAMES = { en: 'English', ro: 'Română', es: 'Español', de: 'Deutsch', fr: 'Français', pt: 'Português' };

function language() {
  const picked = getSettings().lang;
  if (picked && picked !== 'auto' && STRINGS[picked]) return picked;
  let tag = 'en';
  try {
    tag = Spicetify.Locale?.getLocale?.() || navigator.language || 'en';
  } catch {}
  const base = String(tag).toLowerCase().split(/[-_]/)[0];
  return STRINGS[base] ? base : 'en';
}

let lang = null;
onSettings(() => (lang = null));
export function t(key, vars) {
  if (!lang) lang = language();
  let s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}
export const LANGUAGES = Object.keys(STRINGS);
